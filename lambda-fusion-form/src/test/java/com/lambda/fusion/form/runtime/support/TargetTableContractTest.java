package com.lambda.fusion.form.runtime.support;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

import com.baomidou.mybatisplus.core.MybatisConfiguration;
import com.baomidou.mybatisplus.core.MybatisSqlSessionFactoryBuilder;
import com.baomidou.mybatisplus.extension.plugins.MybatisPlusInterceptor;
import com.baomidou.mybatisplus.extension.plugins.handler.TenantLineHandler;
import com.baomidou.mybatisplus.extension.plugins.inner.TenantLineInnerInterceptor;
import com.lambda.autoconfig.MybatisPlusExtendProperties;
import com.lambda.fusion.form.FormProperties;
import com.lambda.fusion.form.design.model.TableColumnView;
import com.lambda.fusion.form.design.support.TableMetadataReader;
import com.lambda.fusion.form.exception.FormBusinessException;
import com.lambda.fusion.form.exception.FormErrorCode;
import java.util.List;
import java.util.Map;
import java.util.UUID;
import java.util.function.Consumer;
import net.sf.jsqlparser.expression.Expression;
import net.sf.jsqlparser.expression.StringValue;
import org.apache.ibatis.mapping.Environment;
import org.apache.ibatis.transaction.jdbc.JdbcTransactionFactory;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.ValueSource;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import tools.jackson.databind.ObjectMapper;

/** JDBC 元数据与实际插件配置的契约测试，覆盖可发布和必须拒绝的物理表。 */
class TargetTableContractTest {

    private JdbcTemplate jdbc;
    private TableMetadataReader reader;
    private TargetTableContract contract;
    private MybatisConfiguration configuration;
    private String tenant = "tenantA";
    private MybatisPlusExtendProperties mybatisProperties;

    @BeforeEach
    void setUp() {
        var source = new DriverManagerDataSource(
                "jdbc:h2:mem:" + UUID.randomUUID() + ";MODE=MySQL;DB_CLOSE_DELAY=-1", "sa", "");
        jdbc = new JdbcTemplate(source);
        FormProperties properties = new FormProperties();
        properties.setAllowedTables(List.of("TARGET_TABLE"));
        reader = new TableMetadataReader(source, properties);
        configuration = new MybatisConfiguration();
        configuration.setEnvironment(new Environment("test", new JdbcTransactionFactory(), source));
        mybatisProperties = new MybatisPlusExtendProperties();
        contract = new TargetTableContract(
                reader, new MybatisSqlSessionFactoryBuilder().build(configuration), mybatisProperties);
    }

    @AfterEach
    void tearDown() {
        jdbc.execute("DROP ALL OBJECTS");
    }

    @Test
    void scopesMetadataToCurrentSchemaAndEscapesWildcardInTableNames() {
        table("ID VARCHAR(32) PRIMARY KEY, NAME VARCHAR(10)");
        jdbc.execute("CREATE SCHEMA OTHER");
        jdbc.execute("CREATE TABLE OTHER.TARGET_TABLE (WRONG_COLUMN INT PRIMARY KEY)");
        jdbc.execute("CREATE TABLE TARGETXTABLE (WRONG_COLUMN INT PRIMARY KEY)");
        assertThat(reader.listTables()).containsExactly("TARGET_TABLE");
        assertThat(reader.listColumns("TARGET_TABLE"))
                .extracting(TableColumnView::getColumnName)
                .containsExactly("ID", "NAME");
        jdbc.execute("DROP TABLE TARGET_TABLE");
        assertThat(reader.listTables()).isEmpty();
        assertThatThrownBy(() -> reader.listColumns("TARGET_TABLE")).isInstanceOf(FormBusinessException.class);
    }

    @ParameterizedTest
    @ValueSource(
            strings = {
                "ID VARCHAR(32), NAME VARCHAR(10)",
                "ID VARCHAR(32), NAME VARCHAR(10), PRIMARY KEY(ID, NAME)",
                "ID VARCHAR(18) PRIMARY KEY, NAME VARCHAR(10)",
                "ID INT PRIMARY KEY, NAME VARCHAR(10)",
                "ID DECIMAL(18,0) PRIMARY KEY, NAME VARCHAR(10)",
                "ID DECIMAL(20,2) PRIMARY KEY, NAME VARCHAR(10)",
                "ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, NAME VARCHAR(10)",
                "ID VARCHAR(32) PRIMARY KEY, NAME INT",
                "ID VARCHAR(32) PRIMARY KEY, NAME VARCHAR(10), MISSING_VALUE INT NOT NULL",
                "ID VARCHAR(32) PRIMARY KEY, NAME VARCHAR(10) GENERATED ALWAYS AS ('generated')"
            })
    void rejectsUnsafePhysicalTables(String ddl) {
        table(ddl);
        assertThatThrownBy(() -> contract.validate(model(snapshot -> {})))
                .isInstanceOf(FormBusinessException.class)
                .satisfies(error -> assertThat(((FormBusinessException) error).getCode())
                        .isEqualTo(FormErrorCode.FORM_TABLE_INVALID.getCode()));
    }

    @ParameterizedTest
    @ValueSource(strings = {"VARCHAR(19)", "CHAR(32)", "BIGINT", "DECIMAL(19,0)"})
    void acceptsIdsThatCanRepresentEverySnowflake(String idType) {
        table("ID " + idType + " PRIMARY KEY, NAME VARCHAR(10)");
        assertThat(contract.validate(model(snapshot -> {}))).containsKeys("ID", "NAME");
    }

    @Test
    void readsRealPrimaryKeyAndAllowsUnmappedDefaultAndGeneratedColumns() {
        table(
                "ID VARCHAR(32) PRIMARY KEY, NAME VARCHAR(10), AMOUNT DECIMAL(8,2) NOT NULL DEFAULT 0.25, COMPUTED INT GENERATED ALWAYS AS (1)");
        Map<String, TableColumnView> columns = contract.validate(model(snapshot -> {}));
        assertThat(columns.get("ID").getPrimaryKey()).isTrue();
        assertThat(columns.get("AMOUNT").getPrimaryKey()).isFalse();
        assertThat(columns.get("AMOUNT").getScale()).isEqualTo(2);
        assertThat(TargetTableContract.hasDefault(columns.get("AMOUNT"))).isTrue();
        assertThat(columns.get("COMPUTED").getGenerated()).isTrue();
    }

    @Test
    void generatedColumnCanBeMappedForReading() {
        table("ID VARCHAR(32) PRIMARY KEY, NAME VARCHAR(10) GENERATED ALWAYS AS ('generated')");
        assertThat(contract.validate(
                        model(snapshot -> snapshot.getFields().getFirst().setPersisted(false))))
                .containsKey("NAME");
    }

    @Test
    void rejectsNullableMismatchAndHiddenRequiredColumnWithoutDefault() {
        table("ID VARCHAR(32) PRIMARY KEY, NAME VARCHAR(10) NOT NULL");
        assertThatThrownBy(() -> contract.validate(
                        model(snapshot -> snapshot.getFields().getFirst().setNullable(true))))
                .isInstanceOf(FormBusinessException.class);
        assertThatThrownBy(() -> contract.validate(model(
                        snapshot -> snapshot.getFields().getFirst().getForm().setShow(false))))
                .isInstanceOf(FormBusinessException.class);
        assertThat(contract.validate(model(snapshot -> {
                    snapshot.getFields().getFirst().getForm().setShow(false);
                    snapshot.getFields().getFirst().setDefaultValue("initial");
                })))
                .containsKey("NAME");
    }

    @Test
    void rejectsHiddenAndReadonlyLogicalRequiredFieldsEvenWhenPhysicalColumnIsNullable() {
        table("ID VARCHAR(32) PRIMARY KEY, NAME VARCHAR(10)");
        assertThatThrownBy(() -> contract.validate(model(
                        snapshot -> snapshot.getFields().getFirst().getForm().setShow(false))))
                .isInstanceOf(FormBusinessException.class);
        assertThatThrownBy(() -> contract.validate(model(
                        snapshot -> snapshot.getFields().getFirst().getForm().setReadonly(true))))
                .isInstanceOf(FormBusinessException.class);
    }

    @Test
    void rejectsDefaultsThatExceedPhysicalLengthOrPrecision() {
        table("ID VARCHAR(32) PRIMARY KEY, NAME VARCHAR(3), AMOUNT DECIMAL(4,2)");
        assertThatThrownBy(() -> contract.validate(
                        model(snapshot -> snapshot.getFields().getFirst().setDefaultValue("long"))))
                .isInstanceOf(FormBusinessException.class);
        for (String value : List.of("100", "1.234")) {
            assertThatThrownBy(() -> contract.validate(model(snapshot -> {
                        var field = snapshot.getFields().getFirst();
                        field.setColumnName("AMOUNT");
                        field.setFieldType("DECIMAL");
                        field.setDefaultValue(value);
                    })))
                    .isInstanceOf(FormBusinessException.class);
        }
    }

    @Test
    void rejectsDecimalMappedToIntegerAndFloatingPointColumns() {
        table("ID VARCHAR(32) PRIMARY KEY, NAME INT, APPROXIMATE DOUBLE");
        for (String column : List.of("NAME", "APPROXIMATE")) {
            assertThatThrownBy(() -> contract.validate(model(snapshot -> {
                        var field = snapshot.getFields().getFirst();
                        field.setColumnName(column);
                        field.setFieldType("DECIMAL");
                    })))
                    .isInstanceOf(FormBusinessException.class);
        }
    }

    @Test
    void skipContractDoesNotBypassTenantPluginOrMissingContext() {
        table("ID VARCHAR(32) PRIMARY KEY, NAME VARCHAR(10)");
        enableTenant(false);
        assertThatThrownBy(() -> contract.validate(model(snapshot -> {}))).isInstanceOf(FormBusinessException.class);
        jdbc.execute("ALTER TABLE TARGET_TABLE ADD TENANT_ID VARCHAR(32)");
        assertThat(contract.validate(model(snapshot -> {}))).containsKey("TENANT_ID");
        tenant = null;
        assertThatThrownBy(() -> contract.validateAccess(model(snapshot -> {})))
                .isInstanceOf(FormBusinessException.class);
        assertThatThrownBy(() -> contract.validate(model(snapshot -> {}))).isInstanceOf(FormBusinessException.class);
    }

    @Test
    void ignoredTenantBearingTableCannotBecomeShared() {
        table("ID VARCHAR(32) PRIMARY KEY, NAME VARCHAR(10), TENANT_ID VARCHAR(32)");
        enableTenant(true);
        assertThatThrownBy(() -> contract.validate(model(snapshot -> {}))).isInstanceOf(FormBusinessException.class);
        jdbc.execute("ALTER TABLE TARGET_TABLE DROP COLUMN TENANT_ID");
        assertThat(contract.validate(model(snapshot -> {}))).containsKey("ID");
        assertThatThrownBy(() -> contract.validate(model(snapshot -> snapshot.setSkipContractColumns(false))))
                .isInstanceOf(FormBusinessException.class);
    }

    @Test
    void normalContractRequiresActiveTenantPluginAndWritableAuditColumns() {
        mybatisProperties.getTenant().setEnabled(true);
        table(
                "ID VARCHAR(32) PRIMARY KEY, NAME VARCHAR(10), TENANT_ID VARCHAR(32), CREATED_BY VARCHAR(32), UPDATED_BY VARCHAR(32), CREATED_AT TIMESTAMP, UPDATED_AT TIMESTAMP");
        var model = model(snapshot -> snapshot.setSkipContractColumns(false));
        assertThatThrownBy(() -> contract.validate(model)).isInstanceOf(FormBusinessException.class);
        enableTenant(false);
        assertThat(contract.validate(model)).containsKey("TENANT_ID");
        jdbc.execute("ALTER TABLE TARGET_TABLE ALTER COLUMN UPDATED_AT VARCHAR(32)");
        assertThatThrownBy(() -> contract.validate(model)).isInstanceOf(FormBusinessException.class);
    }

    @Test
    void disabledTenantModeAllowsNormalAuditContractWithoutTenantContext() {
        tenant = null;
        table(
                "ID VARCHAR(32) PRIMARY KEY, NAME VARCHAR(10), TENANT_ID VARCHAR(32), CREATED_BY VARCHAR(32), UPDATED_BY VARCHAR(32), CREATED_AT TIMESTAMP, UPDATED_AT TIMESTAMP");
        var model = model(snapshot -> snapshot.setSkipContractColumns(false));
        assertThat(contract.validate(model)).containsKeys("ID", "TENANT_ID", "CREATED_AT");
        contract.validateAccess(model);
        jdbc.execute("ALTER TABLE TARGET_TABLE DROP COLUMN TENANT_ID");
        assertThat(contract.validate(model)).doesNotContainKey("TENANT_ID");
    }

    @Test
    void disabledTenantModeStillEnforcesRequiredDatabaseColumns() {
        table("ID VARCHAR(32) PRIMARY KEY, NAME VARCHAR(10), TENANT_ID VARCHAR(32) NOT NULL");
        assertThatThrownBy(() -> contract.validate(model(snapshot -> {})))
                .isInstanceOf(FormBusinessException.class)
                .satisfies(error ->
                        assertThat(((FormBusinessException) error).getArgs()).containsExactly("未赋值的必填列：TENANT_ID"));
        jdbc.execute("ALTER TABLE TARGET_TABLE ALTER COLUMN TENANT_ID SET DEFAULT 'single'");
        assertThat(contract.validate(model(snapshot -> {}))).containsKey("TENANT_ID");
    }

    @Test
    void disabledSettingCannotHideAnInstalledTenantPlugin() {
        table("ID VARCHAR(32) PRIMARY KEY, NAME VARCHAR(10)");
        enableTenant(false);
        mybatisProperties.getTenant().setEnabled(false);
        assertThatThrownBy(() -> contract.validate(model(snapshot -> {})))
                .isInstanceOf(FormBusinessException.class)
                .satisfies(error -> assertThat(((FormBusinessException) error).getArgs())
                        .containsExactly("租户功能已关闭，但目标数据源仍装配租户插件，请检查 MyBatis 配置并重启"));
        assertThatThrownBy(() -> contract.validateAccess(model(snapshot -> {})))
                .isInstanceOf(FormBusinessException.class)
                .satisfies(error -> assertThat(((FormBusinessException) error).getArgs())
                        .containsExactly("租户功能已关闭，但目标数据源仍装配租户插件，请检查 MyBatis 配置并重启"));
    }

    private void enableTenant(boolean ignored) {
        mybatisProperties.getTenant().setEnabled(true);
        MybatisPlusInterceptor interceptor = new MybatisPlusInterceptor();
        interceptor.addInnerInterceptor(new TenantLineInnerInterceptor(new TenantLineHandler() {
            @Override
            public Expression getTenantId() {
                return tenant == null ? null : new StringValue(tenant);
            }

            @Override
            public boolean ignoreTable(String tableName) {
                return tenant == null || ignored;
            }
        }));
        configuration.addInterceptor(interceptor);
    }

    private void table(String columns) {
        jdbc.execute("CREATE TABLE TARGET_TABLE (" + columns + ")");
    }

    private FormModel model(Consumer<FormDefSnapshot> customize) {
        FormDefSnapshot snapshot = new FormDefSnapshot();
        snapshot.setFormKey("test_form");
        snapshot.setFormType("SINGLE");
        snapshot.setTableName("TARGET_TABLE");
        snapshot.setSkipContractColumns(true);
        var field = new FormDefSnapshot.Field();
        field.setFieldName("name");
        field.setColumnName("NAME");
        field.setFieldType("STRING");
        field.setNullable(false);
        snapshot.setFields(List.of(field));
        customize.accept(snapshot);
        SnapshotJson json = new SnapshotJson(new ObjectMapper());
        return new FormModelCompiler(json).compile(json.write(snapshot), 1);
    }
}
